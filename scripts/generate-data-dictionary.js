/**
 * Generates docs/DATA_DICTIONARY.md from public/lib/survey-schema.js.
 * Run `npm run docs` after changing the schema; a test fails if it is stale.
 */
const fs = require('fs');
const path = require('path');
const { STORED_FIELDS, FIELDS_BY_NAME, UNITS, SCHEMA_VERSION, MAX_DAILY_MILES, CHANGELOG, POPULAR_TRAILS, TRAILS } = require('../public/lib/survey-schema');

const OUT_FILE = path.join(__dirname, '../docs/DATA_DICTIONARY.md');

const TYPE_NAMES = {
  enum: 'string (category)',
  enumArray: 'string[] (categories)',
  number: 'number',
  integer: 'integer',
  boolean: 'boolean',
  string: 'string (free text)',
  date: 'date (YYYY-MM-DD)'
};

function describeValues(field) {
  if (field.values) return field.values.map(v => `\`${v}\``).join(', ');
  const parts = [];
  if (field.min !== undefined) {
    const max = typeof field.max === 'function' ? 'current year + 1' : field.max;
    parts.push(`${field.min} – ${max}`);
  }
  if (field.unit) parts.push(UNITS[field.unit].label);
  if (field.maxLength) parts.push(`max ${field.maxLength} chars`);
  return parts.join(' ');
}

function notes(field) {
  const out = [];
  if (field.derived) out.push('Not asked.');
  else if (field.optional) out.push('Optional; null when not answered.');
  else if (field.when) out.push('Required when it applies; null/empty when it does not.');
  else out.push('Required.');
  if (field.allowUnknown) out.push('Can be answered "Don\'t know" (null, listed in `unknownAnswers`).');
  if (field.metricName) out.push(`Metric copy: \`${field.metricName}\` (${UNITS[field.unit].metric}).`);
  if (field.description) out.push(field.description);
  return out.join(' ');
}

function render() {
  const question = f => {
    const q = f.question || (f.questionFrom && FIELDS_BY_NAME[f.questionFrom].question);
    return q ? `"${q.replace(/\|/g, '\\|')}"` : '';
  };
  const rows = STORED_FIELDS.map(f =>
    `| \`${f.name}\` | ${question(f)} | ${TYPE_NAMES[f.type]} | ${describeValues(f)} | ${f.role || ''} | ${notes(f)} |`
  );

  return `<!-- Generated by scripts/generate-data-dictionary.js. Do not edit by hand; run \`npm run docs\`. -->
# Data Dictionary (schema ${SCHEMA_VERSION})

Every record in \`thru_hiker_survey_dataset.json\` / \`.csv\` has these columns, in this order.
Numbers are stored in imperial units; columns listed under "Metric copy" hold the same value in metric.

The stored data and the public files are identical: answers are coarsened before they are saved
(see "Privacy protection" below), and exact dates, exact age, country, free text and the
submission time are never stored.

The first column is \`schemaVersion\`: the schema the record was collected under (see the changelog below).

| Column | Question shown in the survey | Type | Values / units | ML role | Notes |
|---|---|---|---|---|---|
${rows.join('\n')}

Validation also rejects: a ramp-up week count that does not match the dates, an end date before the start date, a start date more than one year
from the hike year, a max load below the base weight, more zero + nero days than days on
trail, an end date in the future, and distances/dates that imply more than ${MAX_DAILY_MILES} mi/day.

In the CSV, list columns (\`injuryLocations\`, \`illnessTypes\`, \`priorInjuryAreas\`, \`deadlineReasons\`,
\`unknownAnswers\`) are \`;\`-separated.

## Privacy protection

- Dates are stored as ISO weeks (\`startWeek\`, \`endWeek\`) and months (\`startMonth\`, \`endMonth\`).
- Popular trails (week precision): ${POPULAR_TRAILS.map(t => `\`${t}\``).join(', ')}.
- All other trails (month precision): ${TRAILS.filter(t => !POPULAR_TRAILS.includes(t)).map(t => `\`${t}\``).join(', ')}.
  On these, \`startWeek\`/\`endWeek\` are null, \`totalDistanceMiles\` is rounded to 10 mi, \`daysOnTrail\` to whole
  weeks, and \`averageDailyMiles\` is computed from the rounded values.
- Asked columns list the exact question; the form shows the unit the hiker chose (imperial or metric).
- Age at the start of the hike is stored as \`ageBand\`: one \`20-and-under\` band, then \`21-24\` and 5-year bands; country as \`homeRegion\`.
- Derived values (\`daysOnTrail\` on popular trails, \`monthsSinceTrail\`, the ramp-up check) are computed from the
  exact answers before those are discarded.

A \`null\` value means the question did not apply, unless the column is listed in
\`unknownAnswers\`, which means the hiker answered "Don't know".

## Changelog

${CHANGELOG.map(e => `### ${e.version} (${e.date})\n\n${e.changes.map(c => `- ${c}`).join('\n')}`).join('\n\n')}
`;
}

if (require.main === module) {
  fs.writeFileSync(OUT_FILE, render(), 'utf-8');
  console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
}

module.exports = { render, OUT_FILE };
